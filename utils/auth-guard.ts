import { createClient } from '@/utils/supabase/server'

/**
 * Assert the caller is a signed-in admin. Server Actions are independently
 * addressable POST endpoints — they do NOT inherit the admin layout's role
 * check — so every privileged action must call this first.
 */
export async function requireAdmin() {
  const supabase = await createClient()

  const {
    data: { user },
  } = await supabase.auth.getUser()

  if (!user) {
    throw new Error('Not authenticated')
  }

  const { data: profile } = await supabase
    .from('profiles')
    .select('role')
    .eq('id', user.id)
    .single()

  if (profile?.role !== 'admin') {
    throw new Error('Not authorized')
  }

  return { supabase, user }
}

/** Assert the caller is signed in. */
export async function requireUser() {
  const supabase = await createClient()
  const {
    data: { user },
  } = await supabase.auth.getUser()

  if (!user) {
    throw new Error('Not authenticated')
  }

  return { supabase, user }
}
